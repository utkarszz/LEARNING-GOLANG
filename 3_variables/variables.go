package main

func main() {
	// Types of variables in GoLang
	// 1. Integer
	var a int = 10
	println(a)
	// 2. Float
	var b float32 = 10.5
	println(b)
	// 3. String
	var c string = "Hello, World!"
	println(c)
	// 4. Boolean
	var d bool = true
	println(d)
	
	// SHORTHAND SYNTAX
	name := "Utkarsh Singh"
	println(name)
	price := 100.5
	println(price)
	isAvailable := true
	println(isAvailable)
	
}